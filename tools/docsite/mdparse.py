@dataclass
class RenderResult:
    html: str
    warnings: list[str]
    footnote_order: list[str]


_ONLY_IMAGE_RE = re.compile(r"^!\[[^\]]*\]\([^)]*\)$")


class Renderer:
    def __init__(
        self,
        ctx: InlineContext,
        highlighter: Callable[[str, str], str],
        heading_offset: int = 0,
    ) -> None:
        self.ctx = ctx
        self.highlight = highlighter
        self.heading_offset = heading_offset

    def render(self, blocks: list[Block]) -> str:
        return "\n".join(self.render_block(block) for block in blocks if block is not None)

    def render_block(self, block: Block, tight: bool = False) -> str:
        kind = block.kind
        if kind == "para":
            inner = render_inline(block.data["raw"], self.ctx)
            if tight:
                return inner
            if _ONLY_IMAGE_RE.match(block.data["raw"].strip()):
                alt = strip_inline(block.data["raw"].strip()[2:].split("]", 1)[0])
                caption = f"<figcaption>{esc_text(alt)}</figcaption>" if alt else ""
                return f"<figure class=\"doc-figure\">{inner}{caption}</figure>"
            return f"<p>{inner}</p>"
        if kind == "heading":
            return self.render_heading(block)
        if kind == "code":
            return self.render_code(block)
        if kind == "hr":
            return "<hr>"
        if kind == "quote":
            return self.render_quote(block)
        if kind == "list":
            return self.render_list(block)
        if kind == "table":
            return self.render_table(block)
        return ""

    def render_heading(self, block: Block) -> str:
        level = min(6, block.data["level"] + self.heading_offset)
        slug = block.data["slug"]
        inner = render_inline(block.data["raw"], self.ctx)
        return (
            f'<h{level} id="{esc_attr(slug)}" class="doc-h">'
            f'<span class="doc-h-text">{inner}</span>'
            f'<a class="doc-anchor" href="#{esc_attr(slug)}" '
            f'aria-label="Link to this section">#</a>'
            f"</h{level}>"
        )

    def render_code(self, block: Block) -> str:
        info = (block.data["info"] or "").strip()
        language = info.split()[0].lower() if info else ""
        content = block.data["content"]
        if language == "mermaid":
            body = self.highlight(content, "mermaid")
            return (
                '<figure class="doc-diagram">'
                '<figcaption><span class="doc-diagram-tag">Diagram</span>'
                "Mermaid source — rendered here as text so the page needs no "
                "diagram library and no network.</figcaption>"
                f'<pre class="doc-pre"><code class="lang-mermaid">{body}</code></pre>'
                "</figure>"
            )
        body = self.highlight(content, language)
        label = esc_text(language or "text")
        return (
            f'<div class="doc-code" data-lang="{esc_attr(language or "text")}">'
            f'<div class="doc-code-bar"><span class="doc-code-lang">{label}</span>'
            f'<button type="button" class="doc-copy" data-copy>'
            f'<span class="doc-copy-label">Copy</span></button></div>'
            f'<pre class="doc-pre"><code class="lang-{esc_attr(language or "text")}">{body}</code></pre>'
            "</div>"
        )

    def render_quote(self, block: Block) -> str:
        alert = block.data.get("alert")
        inner = self.render(block.data["children"])
        if alert:
            tone, word = _ALERT_TONE[alert]
            return (
                f'<div class="doc-alert" data-tone="{esc_attr(tone)}" role="note">'
                f'<p class="doc-alert-head">{esc_text(word)}</p>{inner}</div>'
            )
        return f"<blockquote>{inner}</blockquote>"

    def render_list(self, block: Block) -> str:
        ordered = block.data["ordered"]
        tight = block.data["tight"]
        tasks = block.data["tasks"]
        parts: list[str] = []
        for position, item in enumerate(block.data["items"]):
            task = tasks[position] if position < len(tasks) else None
            rendered: list[str] = []
            for child in item:
                rendered.append(self.render_block(child, tight=tight and child.kind == "para"))
            body = "\n".join(rendered)
            if task is None:
                parts.append(f"<li>{body}</li>")
            else:
                checked = " checked" if task else ""
                state = "done" if task else "todo"
                parts.append(
                    f'<li class="doc-task" data-state="{state}">'
                    f'<input type="checkbox" disabled{checked}>'
                    f"<span>{body}</span></li>"
                )
        classes = ' class="doc-tasklist"' if any(task is not None for task in tasks) else ""
        if ordered:
            start = block.data["start"]
            start_attr = f' start="{start}"' if start != 1 else ""
            return f"<ol{start_attr}{classes}>{''.join(parts)}</ol>"
        return f"<ul{classes}>{''.join(parts)}</ul>"

    def render_table(self, block: Block) -> str:
        aligns = block.data["aligns"]
        header_cells = []
        for position, cell in enumerate(block.data["header"]):
            align = aligns[position] if position < len(aligns) else ""
            attr = f' class="col-{align}"' if align else ""
            header_cells.append(f"<th{attr} scope=\"col\">{render_inline(cell, self.ctx)}</th>")
        body_rows = []
        for row in block.data["rows"]:
            cells = []
            for position, cell in enumerate(row):
                align = aligns[position] if position < len(aligns) else ""
                attr = f' class="col-{align}"' if align else ""
                cells.append(f"<td{attr}>{render_inline(cell, self.ctx)}</td>")
            body_rows.append(f"<tr>{''.join(cells)}</tr>")
        return (
            '<div class="doc-table-wrap"><table>'
            f"<thead><tr>{''.join(header_cells)}</tr></thead>"
            f"<tbody>{''.join(body_rows)}</tbody>"
            "</table></div>"
        )

    def render_footnotes(self, document: Document) -> str:
        if not self.ctx.footnote_order:
            return ""
        items = []
        for label in self.ctx.footnote_order:
            blocks = document.footnote_defs.get(label, [])
            body = self.render(blocks)
            items.append(
                f'<li id="fn-{esc_attr(label)}">{body}'
                f'<a class="fn-back" href="#fnref-{esc_attr(label)}" '
                f'aria-label="Back to reference">&#8617;</a></li>'
            )
        return (
            '<section class="doc-footnotes" id="footnotes">'
            "<h2>Notes</h2><ol>" + "".join(items) + "</ol></section>"
        )


def parse(text: str, warn: Callable[[str], None] | None = None) -> Document:
    collected: list[str] = []
    parser = _BlockParser(warn or collected.append)
    return parser.parse_document(text)


def render(
    document: Document,
    ctx: InlineContext,
    highlighter: Callable[[str, str], str],
    heading_offset: int = 0,
) -> RenderResult:
    renderer = Renderer(ctx, highlighter, heading_offset)
    body = renderer.render(document.blocks)
    footnotes = renderer.render_footnotes(document)
    return RenderResult(
        html=body + footnotes,
        warnings=list(ctx.warnings),
        footnote_order=list(ctx.footnote_order),
    )


def block_text(blocks: list[Block]) -> str:
    """Plain text of a block list — the substance the search index scores on."""
    chunks: list[str] = []
    for block in blocks:
        kind = block.kind
        if kind == "para":
            chunks.append(strip_inline(block.data["raw"]))
        elif kind == "heading":
            chunks.append(block.data["text"])
        elif kind == "code":
            chunks.append(block.data["content"])
        elif kind == "quote":
            chunks.append(block_text(block.data["children"]))
        elif kind == "list":
            for item in block.data["items"]:
                chunks.append(block_text(item))
        elif kind == "table":
            chunks.append(" ".join(strip_inline(cell) for cell in block.data["header"]))
            for row in block.data["rows"]:
                chunks.append(" ".join(strip_inline(cell) for cell in row))
    return "\n".join(chunk for chunk in chunks if chunk)
