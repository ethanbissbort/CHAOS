@dataclass
class Heading:
    level: int
    text: str
    slug: str
    raw: str


@dataclass
class Block:
    kind: str
    # heading: level, raw, slug        code: info, content
    # para: raw                        list: ordered, start, tight, items, tasks
    # quote: children, alert           table: aligns, header, rows
    data: dict


@dataclass
class Document:
    blocks: list[Block]
    headings: list[Heading]
    link_defs: dict[str, tuple[str, str]]
    footnote_defs: dict[str, list[Block]]
    front_matter: dict[str, str]
    title: str | None


_ATX_RE = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?[ \t]*$")
_ATX_CLOSE_RE = re.compile(r"[ \t]+#+[ \t]*$")
_CUSTOM_ID_RE = re.compile(r"[ \t]*\{#([A-Za-z0-9_\-]+)\}[ \t]*$")
_FENCE_RE = re.compile(r"^( {0,3})(`{3,}|~{3,})[ \t]*(.*?)[ \t]*$")
_HR_RE = re.compile(r"^ {0,3}([-*_])[ \t]*(?:\1[ \t]*){2,}$")
_BULLET_RE = re.compile(r"^( {0,3})([-*+])([ \t]+|$)")
_ORDERED_RE = re.compile(r"^( {0,3})(\d{1,9})([.)])([ \t]+|$)")
_QUOTE_RE = re.compile(r"^ {0,3}>[ ]?")
_SETEXT_RE = re.compile(r"^ {0,3}(=+|-+)[ \t]*$")
_TABLE_DELIM_RE = re.compile(r"^ {0,3}\|?[ \t]*:?-+:?[ \t]*(\|[ \t]*:?-+:?[ \t]*)*\|?[ \t]*$")
_LINK_DEF_RE = re.compile(r"^ {0,3}\[([^\]]+)\]:[ \t]*(\S+)(?:[ \t]+[\"'(](.*)[\"')])?[ \t]*$")
_FOOTNOTE_DEF_RE = re.compile(r"^ {0,3}\[\^([^\]\s]+)\]:[ \t]*(.*)$")
_ALERT_RE = re.compile(r"^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\][ \t]*$", re.IGNORECASE)

_ALERT_TONE = {
    "note": ("info", "Note"),
    "tip": ("ok", "Tip"),
    "important": ("major", "Important"),
    "warning": ("warning", "Warning"),
    "caution": ("critical", "Caution"),
}


def _expand_tabs(line: str) -> str:
    """Tabs advance to the next 4-column stop (CommonMark 2.2)."""
    if "\t" not in line:
        return line
    out: list[str] = []
    column = 0
    for char in line:
        if char == "\t":
            width = 4 - (column % 4)
            out.append(" " * width)
            column += width
        else:
            out.append(char)
            column += 1
    return "".join(out)


def _indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _strip_front_matter(lines: list[str]) -> tuple[list[str], dict[str, str]]:
    if not lines or lines[0].rstrip() != "---":
        return lines, {}
    for index in range(1, len(lines)):
        if lines[index].rstrip() in ("---", "..."):
            meta: dict[str, str] = {}
            for raw in lines[1:index]:
                if ":" in raw:
                    key, _, value = raw.partition(":")
                    meta[key.strip()] = value.strip().strip("\"'")
            return lines[index + 1 :], meta
    return lines, {}


class _BlockParser:
    def __init__(self, warn: Callable[[str], None]) -> None:
        self.warn = warn
        self.link_defs: dict[str, tuple[str, str]] = {}
        self.footnote_defs: dict[str, list[Block]] = {}
        self._slugs: dict[str, int] = {}
        self.headings: list[Heading] = []

    # -- entry point ------------------------------------------------------
    def parse_document(self, text: str) -> Document:
        lines = [_expand_tabs(line) for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
        lines, front_matter = _strip_front_matter(lines)
        blocks = self.parse(lines, top_level=True)
        title = front_matter.get("title")
        if title is None:
            for heading in self.headings:
                if heading.level == 1:
                    title = heading.text
                    break
        return Document(
            blocks=blocks,
            headings=self.headings,
            link_defs=self.link_defs,
            footnote_defs=self.footnote_defs,
            front_matter=front_matter,
            title=title,
        )

    # -- slug bookkeeping -------------------------------------------------
    def _unique_slug(self, base: str) -> str:
        if not base:
            base = "section"
        seen = self._slugs.get(base, 0)
        self._slugs[base] = seen + 1
        return base if seen == 0 else f"{base}-{seen}"

    # -- the block loop ---------------------------------------------------
    def parse(self, lines: list[str], top_level: bool = False) -> list[Block]:
        blocks: list[Block] = []
        index = 0
        total = len(lines)
        while index < total:
            line = lines[index]
            if not line.strip():
                index += 1
                continue

            fence = _FENCE_RE.match(line)
            if fence and (fence.group(3) == "" or not fence.group(3).startswith(fence.group(2)[0])):
                index = self._read_fence(lines, index, fence, blocks)
                continue

            atx = _ATX_RE.match(line)
            if atx:
                self._read_atx(atx, blocks)
                index += 1
                continue

            if _HR_RE.match(line) and not _TABLE_DELIM_RE.match(line):
                blocks.append(Block("hr", {}))
                index += 1
                continue

            if _QUOTE_RE.match(line):
                index = self._read_quote(lines, index, blocks)
                continue

            if top_level or True:
                foot = _FOOTNOTE_DEF_RE.match(line)
                if foot:
                    index = self._read_footnote(lines, index, foot)
                    continue

            link_def = _LINK_DEF_RE.match(line)
            if link_def and not line.lstrip().startswith("[^"):
                label = link_def.group(1).strip().lower()
                dest = link_def.group(2).strip("<>")
                self.link_defs.setdefault(label, (dest, link_def.group(3) or ""))
                index += 1
                continue

            if _BULLET_RE.match(line) or _ORDERED_RE.match(line):
                index = self._read_list(lines, index, blocks)
                continue

            if index + 1 < total and "|" in line and _TABLE_DELIM_RE.match(lines[index + 1]):
                consumed = self._read_table(lines, index, blocks)
                if consumed > 0:
                    index = consumed
                    continue

            if _indent_of(line) >= 4:
                index = self._read_indented_code(lines, index, blocks)
                continue

            index = self._read_paragraph(lines, index, blocks)
        return blocks

    # -- individual readers ----------------------------------------------
    def _read_fence(self, lines: list[str], index: int, fence: re.Match[str], blocks: list[Block]) -> int:
        indent = len(fence.group(1))
        marker = fence.group(2)
        info = fence.group(3).strip()
        body: list[str] = []
        cursor = index + 1
        while cursor < len(lines):
            candidate = lines[cursor]
            closing = _FENCE_RE.match(candidate)
            if (
                closing
                and closing.group(2)[0] == marker[0]
                and len(closing.group(2)) >= len(marker)
                and not closing.group(3)
            ):
                cursor += 1
                break
            body.append(candidate[indent:] if candidate[:indent].strip() == "" else candidate.lstrip(" "))
            cursor += 1
        blocks.append(Block("code", {"info": info, "content": "\n".join(body)}))
        return cursor

    def _read_atx(self, atx: re.Match[str], blocks: list[Block]) -> None:
        level = len(atx.group(1))
        raw = (atx.group(2) or "").strip()
        raw = _ATX_CLOSE_RE.sub("", raw)
        custom = _CUSTOM_ID_RE.search(raw)
        explicit = None
        if custom:
            explicit = custom.group(1)
            raw = raw[: custom.start()].rstrip()
        self._emit_heading(level, raw, explicit, blocks)

    def _emit_heading(self, level: int, raw: str, explicit: str | None, blocks: list[Block]) -> None:
        text = strip_inline(raw)
        slug = self._unique_slug(explicit or slugify(text))
        self.headings.append(Heading(level=level, text=text, slug=slug, raw=raw))
        blocks.append(Block("heading", {"level": level, "raw": raw, "slug": slug, "text": text}))

    def _read_quote(self, lines: list[str], index: int, blocks: list[Block]) -> int:
        inner: list[str] = []
        cursor = index
        while cursor < len(lines):
            line = lines[cursor]
            marker = _QUOTE_RE.match(line)
            if marker:
                inner.append(line[marker.end() :])
                cursor += 1
                continue
            # Lazy continuation: a plain paragraph line directly under a quote
            # line stays inside the quote (CommonMark 5.1).
            if line.strip() and inner and inner[-1].strip() and not _starts_block(line):
                inner.append(line.strip())
                cursor += 1
                continue
            break
        alert = None
        if inner:
            match = _ALERT_RE.match(inner[0].strip())
            if match:
                alert = match.group(1).lower()
                inner = inner[1:]
        blocks.append(Block("quote", {"children": self.parse(inner), "alert": alert}))
        return cursor

    def _read_footnote(self, lines: list[str], index: int, match: re.Match[str]) -> int:
        label = match.group(1)
        body = [match.group(2)]
        cursor = index + 1
        while cursor < len(lines):
            line = lines[cursor]
            if not line.strip():
                nxt = cursor + 1
                while nxt < len(lines) and not lines[nxt].strip():
                    nxt += 1
                if nxt < len(lines) and _indent_of(lines[nxt]) >= 4:
                    body.append("")
                    cursor += 1
                    continue
                break
            if _indent_of(line) >= 4:
                body.append(line[4:])
                cursor += 1
                continue
            break
        self.footnote_defs.setdefault(label, self.parse(body))
        return cursor

    def _read_indented_code(self, lines: list[str], index: int, blocks: list[Block]) -> int:
        body: list[str] = []
        cursor = index
        while cursor < len(lines):
            line = lines[cursor]
            if not line.strip():
                body.append("")
                cursor += 1
                continue
            if _indent_of(line) < 4:
                break
            body.append(line[4:])
            cursor += 1
        while body and not body[-1].strip():
            body.pop()
        blocks.append(Block("code", {"info": "", "content": "\n".join(body)}))
        return cursor

    def _read_table(self, lines: list[str], index: int, blocks: list[Block]) -> int:
        header = split_table_row(lines[index])
        aligns = _table_alignments(lines[index + 1])
        if len(aligns) != len(header):
            return 0
        rows: list[list[str]] = []
        cursor = index + 2
        while cursor < len(lines):
            line = lines[cursor]
            if not line.strip() or "|" not in line or _starts_block(line):
                break
            cells = split_table_row(line)
            if len(cells) < len(header):
                cells = cells + [""] * (len(header) - len(cells))
            elif len(cells) > len(header):
                cells = cells[: len(header)]
            rows.append(cells)
            cursor += 1
        blocks.append(Block("table", {"aligns": aligns, "header": header, "rows": rows}))
        return cursor

    def _read_paragraph(self, lines: list[str], index: int, blocks: list[Block]) -> int:
        body: list[str] = [lines[index].strip()]
        cursor = index + 1
        while cursor < len(lines):
            line = lines[cursor]
            if not line.strip():
                break
            setext = _SETEXT_RE.match(line)
            if setext:
                level = 1 if setext.group(1)[0] == "=" else 2
                self._emit_heading(level, " ".join(body).strip(), None, blocks)
                return cursor + 1
            if _starts_block(line):
                break
            if cursor + 1 < len(lines) and "|" in line and _TABLE_DELIM_RE.match(lines[cursor + 1]):
                break
            body.append(line.rstrip() if line.rstrip().endswith("\\") else line)
            cursor += 1
        blocks.append(Block("para", {"raw": "\n".join(part.rstrip() for part in body).strip()}))
        return cursor

    # -- lists ------------------------------------------------------------
    def _read_list(self, lines: list[str], index: int, blocks: list[Block]) -> int:
        first_bullet = _BULLET_RE.match(lines[index])
        first_ordered = _ORDERED_RE.match(lines[index])
        ordered = first_ordered is not None
        if ordered:
            assert first_ordered is not None
            start = int(first_ordered.group(2))
            delimiter = first_ordered.group(3)
            bullet_char = ""
        else:
            assert first_bullet is not None
            start = 1
            delimiter = ""
            bullet_char = first_bullet.group(2)

        items: list[list[str]] = []
        tasks: list[bool | None] = []
        loose = False
        cursor = index
        total = len(lines)

        while cursor < total:
            line = lines[cursor]
            match = _ORDERED_RE.match(line) if ordered else _BULLET_RE.match(line)
            if not match:
                break
            if ordered:
                if match.group(3) != delimiter:
                    break
            elif match.group(2) != bullet_char:
                break

            content_indent = match.end()
            if match.group(len(match.groups())) == "":
                content_indent = len(match.group(0)) + 1
            item_lines = [line[content_indent:]]
            cursor += 1
            pending_blanks = 0
            while cursor < total:
                candidate = lines[cursor]
                if not candidate.strip():
                    pending_blanks += 1
                    cursor += 1
                    continue
                if _indent_of(candidate) >= content_indent:
                    if pending_blanks:
                        item_lines.extend([""] * pending_blanks)
                        loose = True
                        pending_blanks = 0
                    item_lines.append(candidate[content_indent:])
                    cursor += 1
                    continue
                if pending_blanks:
                    break
                if _starts_block(candidate):
                    break
                item_lines.append(candidate.strip())
                cursor += 1
            if pending_blanks:
                cursor -= pending_blanks
                # A blank line before the next item of the same list makes the
                # whole list loose; before anything else it just ends the list.
                nxt = cursor + pending_blanks
                if nxt < total:
                    following = _ORDERED_RE.match(lines[nxt]) if ordered else _BULLET_RE.match(lines[nxt])
                    if following:
                        loose = True
                        cursor = nxt
            task = None
            if item_lines:
                task_match = re.match(r"^\[([ xX])\][ \t]+", item_lines[0])
                if task_match:
                    task = task_match.group(1).lower() == "x"
                    item_lines[0] = item_lines[0][task_match.end() :]
            items.append(item_lines)
            tasks.append(task)

        parsed = [self.parse(item) for item in items]
        blocks.append(
            Block(
                "list",
                {
                    "ordered": ordered,
                    "start": start,
                    "tight": not loose,
                    "items": parsed,
                    "tasks": tasks,
                },
            )
        )
        return cursor


def _starts_block(line: str) -> bool:
    """True when ``line`` cannot be a lazy paragraph continuation."""
    return bool(
        _ATX_RE.match(line)
        or _FENCE_RE.match(line)
        or _HR_RE.match(line)
        or _QUOTE_RE.match(line)
        or _BULLET_RE.match(line)
        or _ORDERED_RE.match(line)
    )


def split_table_row(line: str) -> list[str]:
    text = line.strip()
    if text.startswith("|"):
        text = text[1:]
    if text.endswith("|") and not text.endswith("\\|"):
        text = text[:-1]
    cells: list[str] = []
    buffer: list[str] = []
    index = 0
    while index < len(text):
        char = text[index]
        if char == "\\" and index + 1 < len(text) and text[index + 1] == "|":
            buffer.append("|")
            index += 2
            continue
        if char == "|":
            cells.append("".join(buffer))
            buffer = []
            index += 1
            continue
        buffer.append(char)
        index += 1
    cells.append("".join(buffer))
    return [cell.strip() for cell in cells]


def _table_alignments(line: str) -> list[str]:
    aligns: list[str] = []
    for cell in split_table_row(line):
        left = cell.startswith(":")
        right = cell.endswith(":")
        if left and right:
            aligns.append("center")
        elif right:
            aligns.append("right")
        elif left:
            aligns.append("left")
        else:
            aligns.append("")
    return aligns


