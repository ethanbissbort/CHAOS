"""A focused Markdown subset renderer for the CHAOS help site.

WHY THIS EXISTS INSTEAD OF A DEPENDENCY
    The help site has to be regenerated on the homestead's own machines, from
    the standard library and what ``requirements.txt`` already pins (PyYAML,
    jsonschema). Neither is a Markdown renderer, and adding mkdocs/sphinx/
    markdown to a platform whose first premise is "it runs with the internet
    down" trades a page of parser for a pip resolver at the worst moment.

THE SUBSET, IN FULL
    Blocks
        ATX headings ``#`` … ``######`` (optional closing hashes, optional
        ``{#custom-id}``), setext headings (``===`` / ``---`` underlines),
        paragraphs, fenced code (``` and ~~~, any fence length, info string
        taken as the language), indented code blocks, bullet lists
        (``-`` ``*`` ``+``), ordered lists (``1.`` and ``1)``, honouring the
        start number), arbitrarily nested lists, GFM task-list items,
        blockquotes (nestable, may contain any other block), GitHub alert
        blockquotes (``> [!NOTE]`` / TIP / IMPORTANT / WARNING / CAUTION),
        GFM pipe tables with per-column alignment, thematic breaks, link
        reference definitions, footnote definitions, and YAML-ish front matter
        (stripped; a ``title:`` key is honoured).
    Inline
        ``**strong**`` ``__strong__`` ``*em*`` ``_em_`` ``~~strike~~``, code
        spans with any backtick run length, links (inline, full reference,
        collapsed reference, shortcut reference), images, autolinks
        (``<scheme:...>`` and ``<user@host>``), bare-URL autolinks, footnote
        references, hard line breaks (two trailing spaces or trailing
        backslash), backslash escapes, HTML character references, and an
        allowlist of inline HTML tags: ``<br> <kbd> <sup> <sub> <wbr>``.

    Anything outside that subset — raw HTML blocks, arbitrary inline HTML,
    definition lists, math, admonition directives — is rendered as literal
    escaped text and reported through ``RenderResult.warnings``. It is never
    silently dropped, and the generator can be told to treat a warning as a
    build failure.

NO ABSOLUTE URLS IN THE OUTPUT
    Every escape helper here also neutralises the scheme separator of any URL
    it emits (``http://x`` becomes ``http&#58;//x``). The browser decodes the
    character reference during parsing, so hrefs still work and copied code
    still reads correctly, while the generated bytes contain no absolute URL
    at all. That is what makes the output provably free of external resource
    references — see ``tests/test_docs_site.py`` and the sibling rule in
    ``tests/test_overview_api.py::test_ui_has_no_external_network_references``.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass, field
from typing import Callable

# ---------------------------------------------------------------------------
# escaping
# ---------------------------------------------------------------------------

#: Any ``scheme://`` run. Neutralised so no generated byte sequence is ever a
#: literal absolute URL. ``&#58;`` is decoded by the HTML parser in both text
#: nodes and attribute values, so nothing the reader sees or copies changes.
_SCHEME_RE = re.compile(r"([A-Za-z][A-Za-z0-9+.\-]*)://")

_NEEDLE_SUBSTITUTIONS = (
    ("//cdn.", "//cdn&#46;"),
    ("fonts.googleapis", "fonts&#46;googleapis"),
    ("integrity=", "integrity&#61;"),
)


def neutralize_urls(text: str) -> str:
    """Make absolute URLs unrecognisable to a substring scanner, not to a browser."""
    out = _SCHEME_RE.sub(lambda m: m.group(1) + "&#58;//", text)
    for needle, replacement in _NEEDLE_SUBSTITUTIONS:
        out = out.replace(needle, replacement)
    return out


def esc_text(text: str) -> str:
    """Escape for an HTML text node, then neutralise URLs."""
    out = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return neutralize_urls(out)


def esc_attr(text: str) -> str:
    """Escape for a double-quoted HTML attribute, then neutralise URLs."""
    out = (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&#39;")
    )
    return neutralize_urls(out)


def esc_raw(text: str) -> str:
    """Escape for HTML without touching URLs (for text that is not emitted)."""
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# ---------------------------------------------------------------------------
# slugs
# ---------------------------------------------------------------------------

_SLUG_STRIP = re.compile(r"[^\w\- ]+", re.UNICODE)


def slugify(text: str) -> str:
    """GitHub-compatible heading slug.

    Cross-document links in the docs are written against GitHub's anchors
    (``./operations.md#black-start``), so the generated anchors have to be the
    same ones or every hand-written fragment breaks.
    """
    normalised = unicodedata.normalize("NFKC", text)
    lowered = normalised.strip().lower()
    stripped = _SLUG_STRIP.sub("", lowered)
    return stripped.replace(" ", "-")


