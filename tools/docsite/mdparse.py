@dataclass
class LinkTarget:
    """What the site decided a Markdown destination points at."""

    href: str
    kind: str = "external"  # page | anchor | external | repo | broken
    title: str = ""
    label: str = ""


@dataclass
class InlineContext:
    """Everything ``render_inline`` needs from the surrounding build."""

    resolve_link: Callable[[str, str], LinkTarget]
    resolve_image: Callable[[str, str], LinkTarget]
    link_defs: dict[str, tuple[str, str]] = field(default_factory=dict)
    footnote_defs: dict[str, list[Block]] = field(default_factory=dict)
    footnote_order: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def footnote_number(self, label: str) -> int:
        if label not in self.footnote_order:
            self.footnote_order.append(label)
        return self.footnote_order.index(label) + 1


def strip_inline(text: str) -> str:
    """Plain-text form of an inline run — used for slugs, titles and search."""
    out = text
    out = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", out)
    out = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", out)
    out = re.sub(r"\[([^\]]*)\]\[[^\]]*\]", r"\1", out)
    out = re.sub(r"\[\^[^\]]+\]", "", out)
    out = re.sub(r"</?[A-Za-z][^>]*>", "", out)
    out = out.replace("`", "")
    out = re.sub(r"\*\*|__|~~", "", out)
    out = re.sub(r"(?<![\w\\])[*_](?=\S)", "", out)
    out = re.sub(r"(?<=\S)[*_](?![\w])", "", out)
    out = re.sub(r"\\([!-/:-@\[-`{-~])", r"\1", out)
    return " ".join(out.split())


def _find_close_bracket(src: str, start: int) -> int:
    depth = 0
    index = start
    length = len(src)
    while index < length:
        char = src[index]
        if char == "\\":
            index += 2
            continue
        if char == "`":
            run = _BACKTICKS_RE.match(src, index)
            assert run is not None
            close = src.find(run.group(0), run.end())
            index = run.end() if close == -1 else close + len(run.group(0))
            continue
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
            if depth == 0:
                return index
        index += 1
    return -1


def _parse_destination(src: str, start: int) -> tuple[str, str, int] | None:
    """Parse ``(dest "title")`` beginning at ``src[start] == '('``."""
    index = start + 1
    length = len(src)
    while index < length and src[index] in " \t\n":
        index += 1
    if index < length and src[index] == "<":
        close = src.find(">", index)
        if close == -1:
            return None
        dest = src[index + 1 : close]
        index = close + 1
    else:
        depth = 0
        begin = index
        while index < length:
            char = src[index]
            if char == "\\":
                index += 2
                continue
            if char in " \t\n" and depth == 0:
                break
            if char == "(":
                depth += 1
            elif char == ")":
                if depth == 0:
                    break
                depth -= 1
            index += 1
        dest = src[begin:index]
    rest_start = index
    depth = 0
    while index < length:
        char = src[index]
        if char == "\\":
            index += 2
            continue
        if char == "(":
            depth += 1
        elif char == ")":
            if depth == 0:
                break
            depth -= 1
        index += 1
    if index >= length:
        return None
    remainder = src[rest_start:index]
    title = ""
    if remainder.strip():
        match = _TITLE_RE.match(remainder)
        if match is None:
            return None
        title = next(group for group in match.groups() if group is not None)
    return dest.strip(), title, index + 1


def render_inline(src: str, ctx: InlineContext, in_link: bool = False) -> str:
    out: list[str] = []
    index = 0
    length = len(src)
    last_text_slot = -1

    def emit_text(chunk: str) -> None:
        nonlocal last_text_slot
        if chunk:
            out.append(esc_text(chunk))
            last_text_slot = len(out) - 1

    while index < length:
        match = _SCAN_RE.search(src, index)
        if match is None:
            emit_text(src[index:])
            break
        emit_text(src[index : match.start()])
        index = match.start()
        char = src[index]

        if char == "h":
            bare = _BARE_URL_RE.match(src, index)
            if bare and not in_link:
                target = ctx.resolve_link(bare.group(0), bare.group(0))
                out.append(_render_anchor(target, esc_text(bare.group(0))))
                index = bare.end()
                continue
            emit_text(src[index : index + 1])
            index += 1
            continue

        if char == "\\":
            if index + 1 < length and src[index + 1] == "\n":
                out.append("<br>\n")
                index += 2
                continue
            if index + 1 < length and src[index + 1] in _PUNCT:
                emit_text(src[index + 1])
                index += 2
                continue
            emit_text("\\")
            index += 1
            continue

        if char == "\n":
            if index >= 2 and src[index - 1] == " " and src[index - 2] == " ":
                if last_text_slot >= 0:
                    out[last_text_slot] = out[last_text_slot].rstrip(" ")
                out.append("<br>\n")
                index += 1
                continue
            emit_text("\n")
            index += 1
            continue

        if char == "`":
            run = _BACKTICKS_RE.match(src, index)
            assert run is not None
            ticks = run.group(0)
            close = src.find(ticks, run.end())
            while close != -1 and close + len(ticks) < length and src[close + len(ticks)] == "`":
                close = src.find(ticks, close + len(ticks) + 1)
            if close == -1:
                emit_text(ticks)
                index = run.end()
                continue
            content = src[run.end() : close].replace("\n", " ")
            if len(content) > 1 and content.startswith(" ") and content.endswith(" ") and content.strip():
                content = content[1:-1]
            out.append(f"<code>{esc_text(content)}</code>")
            index = close + len(ticks)
            continue

        if char == "<":
            uri = _AUTOLINK_URI_RE.match(src, index)
            if uri:
                target = ctx.resolve_link(uri.group(1), uri.group(1))
                out.append(_render_anchor(target, esc_text(uri.group(1))))
                index = uri.end()
                continue
            mail = _AUTOLINK_MAIL_RE.match(src, index)
            if mail:
                target = LinkTarget(href="mailto:" + mail.group(1), kind="external")
                out.append(_render_anchor(target, esc_text(mail.group(1))))
                index = mail.end()
                continue
            html = _INLINE_HTML_RE.match(src, index)
            if html:
                out.append(html.group(0).lower())
                index = html.end()
                continue
            tagish = re.match(r"</?[A-Za-z][^>\n]*>", src[index:])
            if tagish:
                ctx.warnings.append(f"raw inline HTML rendered as text: {tagish.group(0)!r}")
            emit_text("<")
            index += 1
            continue

        if char == "&":
            entity = _ENTITY_RE.match(src, index)
            if entity:
                out.append(entity.group(0))
                index = entity.end()
                continue
            emit_text("&")
            index += 1
            continue

        if char == "!":
            if index + 1 < length and src[index + 1] == "[":
                handled = _render_link(src, index + 1, ctx, out, image=True, in_link=in_link)
                if handled is not None:
                    index = handled
                    continue
            emit_text("!")
            index += 1
            continue

        if char == "[":
            handled = _render_link(src, index, ctx, out, image=False, in_link=in_link)
            if handled is not None:
                index = handled
                continue
            emit_text("[")
            index += 1
            continue

        if char == "~":
            strike = _STRIKE_RE.match(src, index)
            if strike:
                out.append(f"<del>{render_inline(strike.group(1), ctx, in_link)}</del>")
                index = strike.end()
                continue
            emit_text("~")
            index += 1
            continue

        if char == "*":
            strong = _STRONG_STAR_RE.match(src, index)
            if strong:
                out.append(f"<strong>{render_inline(strong.group(1), ctx, in_link)}</strong>")
                index = strong.end()
                continue
            emphasis = _EM_STAR_RE.match(src, index)
            if emphasis:
                out.append(f"<em>{render_inline(emphasis.group(1), ctx, in_link)}</em>")
                index = emphasis.end()
                continue
            emit_text("*")
            index += 1
            continue

        if char == "_":
            before_ok = index == 0 or not _WORDISH.match(src[index - 1])
            if before_ok:
                strong = _STRONG_UNDER_RE.match(src, index)
                if strong and not _WORDISH.match(src[strong.end() : strong.end() + 1] or " "):
                    out.append(f"<strong>{render_inline(strong.group(1), ctx, in_link)}</strong>")
                    index = strong.end()
                    continue
                emphasis = _EM_UNDER_RE.match(src, index)
                if emphasis and not _WORDISH.match(src[emphasis.end() : emphasis.end() + 1] or " "):
                    out.append(f"<em>{render_inline(emphasis.group(1), ctx, in_link)}</em>")
                    index = emphasis.end()
                    continue
            emit_text("_")
            index += 1
            continue

        emit_text(char)
        index += 1

    return "".join(out)


def _render_anchor(target: LinkTarget, inner_html: str, extra_class: str = "") -> str:
    classes = []
    if target.kind == "external":
        classes.append("x-link")
    elif target.kind == "repo":
        classes.append("repo-link")
    if extra_class:
        classes.append(extra_class)
    if target.kind == "repo":
        title = target.title or "Repository path — not part of this help set"
        return (
            f'<span class="repo-ref" title="{esc_attr(title)}">'
            f'<code>{inner_html}</code></span>'
        )
    attrs = f' class="{" ".join(classes)}"' if classes else ""
    title = f' title="{esc_attr(target.title)}"' if target.title else ""
    external = ' rel="noreferrer noopener"' if target.kind == "external" else ""
    return f'<a href="{esc_attr(target.href)}"{attrs}{title}{external}>{inner_html}</a>'


def _render_link(
    src: str,
    open_bracket: int,
    ctx: InlineContext,
    out: list[str],
    image: bool,
    in_link: bool,
) -> int | None:
    close = _find_close_bracket(src, open_bracket)
    if close == -1:
        return None
    label = src[open_bracket + 1 : close]

    if not image and label.startswith("^"):
        key = label[1:]
        if key in ctx.footnote_defs:
            number = ctx.footnote_number(key)
            out.append(
                f'<sup class="fn-ref" id="fnref-{esc_attr(key)}">'
                f'<a href="#fn-{esc_attr(key)}" aria-describedby="footnotes">{number}</a></sup>'
            )
            return close + 1
        return None

    after = close + 1
    dest: str | None = None
    title = ""
    if after < len(src) and src[after] == "(":
        parsed = _parse_destination(src, after)
        if parsed is None:
            return None
        dest, title, after = parsed
    elif after < len(src) and src[after] == "[":
        ref_close = src.find("]", after)
        if ref_close == -1:
            return None
        ref = src[after + 1 : ref_close].strip().lower() or label.strip().lower()
        if ref not in ctx.link_defs:
            return None
        dest, title = ctx.link_defs[ref]
        after = ref_close + 1
    else:
        ref = label.strip().lower()
        if ref in ctx.link_defs:
            dest, title = ctx.link_defs[ref]
        else:
            return None

    if image:
        target = ctx.resolve_image(dest, label)
        target.title = target.title or title
        alt = esc_attr(strip_inline(label))
        title_attr = f' title="{esc_attr(target.title)}"' if target.title else ""
        out.append(f'<img src="{esc_attr(target.href)}" alt="{alt}"{title_attr} loading="lazy">')
        return after

    target = ctx.resolve_link(dest, label)
    target.title = target.title or title
    inner = render_inline(label, ctx, in_link=True)
    if in_link:
        out.append(inner)
    else:
        out.append(_render_anchor(target, inner))
    return after


